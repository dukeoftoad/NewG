#!/usr/bin/env python3
"""Generate the ToadMark token consumers from design/tokens/toadmark.json.

The JSON is the single source of truth; the Kotlin and Dart files below are
deterministic, committed artifacts. To change a value, edit the JSON, re-run
this script, and commit all three files together:

    python3 scripts/gen_tokens.py

The drift test (ToadMarkTokensTest) fails CI when the committed artifacts
stop matching the JSON.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS_JSON = ROOT / "design" / "tokens" / "toadmark.json"
KT_OUT = ROOT / "app/src/main/java/com/toadgallery/app/ui/theme/ToadMarkTokens.kt"
DART_OUT = ROOT / "design/flutter/toadmark_tokens.dart"

REQUIRED_SECTIONS = ("color", "radius", "gap", "touch", "motion", "row", "badge", "type")

GEN_HEADER = "GENERATED by scripts/gen_tokens.py from design/tokens/toadmark.json — edit the JSON, not this file."


def fail(msg: str) -> None:
    print(f"gen_tokens: {msg}", file=sys.stderr)
    sys.exit(1)


def load() -> dict:
    try:
        data = json.loads(TOKENS_JSON.read_text(encoding="utf-8"))
    except FileNotFoundError:
        fail(f"token source not found: {TOKENS_JSON}")
    for section in REQUIRED_SECTIONS:
        if section not in data:
            fail(f"missing required section '{section}' in toadmark.json")
    return data


def argb(hexstr: str) -> int:
    """#RRGGBB -> 0xAARRGGBB for Kotlin Color(Long) and Dart Color(0x...)."""
    m = re.fullmatch(r"#([0-9A-Fa-f]{6})", hexstr)
    if not m:
        fail(f"bad hex color '{hexstr}' (expected #RRGGBB)")
    return 0xFF000000 | int(m.group(1), 16)


def camel(snake: str) -> str:
    """camelCase key -> PascalCase (pondDeep -> PondDeep)."""
    return snake[0].upper() + snake[1:]


def color_tokens(data: dict) -> list[tuple[str, str, str]]:
    """(kotlinName, dartName, #RRGGBB) for every color token, in file order."""
    color = data["color"]
    out: list[tuple[str, str, str]] = []
    for group in ("light", "dark", "accent", "neutral"):
        for name, value in color[group].items():
            if not isinstance(value, str):
                fail(f"color.{group}.{name} must be a #RRGGBB string")
            suffix = (group.title() if group in ("light", "dark") else "") + camel(name)
            out.append((f"ToadMark{suffix}", f"toadmark{suffix}", value))
    return out


def num_tokens(data: dict) -> list[tuple[str, str, int, str]]:
    """(kotlinName, dartName, value, comment) for every numeric token."""
    r, g, m, row, badge = data["radius"], data["gap"], data["motion"], data["row"], data["badge"]
    out: list[tuple[str, str, int, str]] = [
        ("RadiusBadge", "radiusBadge", r["badge"], "Inline chips and quality pills inside dense rows."),
        ("RadiusThumb", "radiusThumb", r["thumb"], "Small square artwork in list rows and grid cells."),
        ("RadiusCover", "radiusCover", r["cover"], "Large artwork: detail headers, lightbox chrome."),
        ("RadiusControl", "radiusControl", r["control"], "Buttons, text fields and other interactive controls."),
        ("RadiusCard", "radiusCard", r["card"], "Grouped containers: settings groups, section cards."),
        ("RadiusSheet", "radiusSheet", r["sheet"], "Modal bottom sheets and matching search fields."),
        ("GapXs", "gapXs", g["xs"], "Hairline gaps inside a component."),
        ("GapSm", "gapSm", g["sm"], "Gap between sibling controls."),
        ("GapMd", "gapMd", g["md"], "Default inset between a component and its neighbors."),
        ("GapLg", "gapLg", g["lg"], "Card and section padding."),
        ("GapXl", "gapXl", g["xl"], "Screen-level breathing room."),
        ("MinTouchTarget", "minTouchTarget", data["touch"]["minTarget"], "Material's minimum interactive size."),
        ("RowPaddingH", "rowPaddingH", row["paddingH"], "Horizontal inset of settings-style rows."),
        ("RowPaddingV", "rowPaddingV", row["paddingV"], "Vertical inset of tappable settings rows."),
        ("RowPaddingVCompact", "rowPaddingVCompact", row["paddingVCompact"], "Vertical inset of rows with a tall trailing control."),
        ("RowIconGap", "rowIconGap", row["iconGap"], "Space between a row's leading icon and its text."),
        ("RowIconDividerIndent", "rowIconDividerIndent", row["iconDividerIndent"], "Divider start indent so the line starts under the text."),
        ("RowChevronSize", "rowChevronSize", row["chevronSize"], "Disclosure chevron on navigable rows."),
        ("BadgeFontSize", "badgeFontSize", badge["fontSize"], "Badge/pill text size (sp)."),
        ("BadgePaddingH", "badgePaddingH", badge["paddingH"], "Badge horizontal padding."),
        ("BadgePaddingV", "badgePaddingV", badge["paddingV"], "Badge vertical padding."),
        ("MotionFast", "motionFast", m["durationMs"]["fast"], "Fast spec: chips, checks, small feedback."),
        ("MotionMedium", "motionMedium", m["durationMs"]["medium"], "Default spec: panels, nav transitions, content changes."),
        ("MotionSlow", "motionSlow", m["durationMs"]["slow"], "Slow spec: full-screen surfaces."),
    ]
    return out


def springs(data: dict) -> list[tuple[str, float, float]]:
    s = data["motion"]["spring"]
    out = []
    for name in ("spatialFast", "spatialDefault", "spatialSlow", "effectsFast", "effectsDefault"):
        spec = s[name]
        out.append((camel(name), float(spec["dampingRatio"]), float(spec["stiffness"])))
    return out


def generate_kotlin(data: dict) -> str:
    colors = color_tokens(data)
    nums = num_tokens(data)
    spr = springs(data)
    lines: list[str] = []
    w = lines.append
    w("package com.toadgallery.app.ui.theme")
    w("")
    w("import androidx.compose.animation.core.SpringSpec")
    w("import androidx.compose.animation.core.spring")
    w("import androidx.compose.ui.unit.dp")
    w("import androidx.compose.ui.unit.sp")
    w("")
    w("/*")
    w(f" * {GEN_HEADER}")
    w(" *")
    w(" * ToadMark is the shared toad-family design language. The palette values come")
    w(" * from toadPLAYER's ToadTheme (LGPL-3.0-only, zarzet) and toadHEALTH's ToadColors")
    w(" * (MIT, dukeoftoad), re-expressed; metrics follow toadPLAYER's AppTokens. No")
    w(" * upstream code is copied.")
    w(" */")
    w("object ToadMarkTokens {")
    # Colors
    w("  // Palette")
    for kt_name, dart_name, hexval in colors:
        w(f"  const val {kt_name} = 0x{argb(hexval):08X}L  // {hexval.upper()}")
    w("")
    # Numerics as dp/sp/Int/Long
    w("  // Metrics")
    for kt_name, dart_name, value, comment in nums:
        if kt_name.startswith("Radius") or kt_name.startswith("Gap") or kt_name.startswith("Row") or kt_name in ("MinTouchTarget",):
            unit = "dp"
        elif kt_name.startswith("Badge"):
            unit = "sp" if kt_name == "BadgeFontSize" else "dp"
        elif kt_name.startswith("Motion"):
            unit = "Int"  # milliseconds, plain Int for MotionPolicy
        else:
            unit = "Int"
        if kt_name.startswith("Motion"):
            w(f"  val {kt_name} = {value}  // ms — {comment}")
        else:
            w(f"  val {kt_name} = {value}.{unit}  // {comment}")
    w("")
    w("  // Springs: spatial overshoot slightly, effects settle flat (M3-Expressive split)")
    for name, damping, stiffness in spr:
        w(f"  const val Spring{name}Damping = {damping}f")
    for name, damping, stiffness in spr:
        w(f"  const val Spring{name}Stiffness = {stiffness}f")
    w("")
    w("  fun springSpatialFast(): SpringSpec<Float> =")
    w("    spring(dampingRatio = SpringSpatialFastDamping, stiffness = SpringSpatialFastStiffness)")
    w("")
    w("  fun springSpatialDefault(): SpringSpec<Float> =")
    w("    spring(dampingRatio = SpringSpatialDefaultDamping, stiffness = SpringSpatialDefaultStiffness)")
    w("")
    w("  fun springSpatialSlow(): SpringSpec<Float> =")
    w("    spring(dampingRatio = SpringSpatialSlowDamping, stiffness = SpringSpatialSlowStiffness)")
    w("")
    w("  fun springEffectsFast(): SpringSpec<Float> =")
    w("    spring(dampingRatio = SpringEffectsFastDamping, stiffness = SpringEffectsFastStiffness)")
    w("")
    w("  fun springEffectsDefault(): SpringSpec<Float> =")
    w("    spring(dampingRatio = SpringEffectsDefaultDamping, stiffness = SpringEffectsDefaultStiffness)")
    w("}")
    return "\n".join(lines) + "\n"


def generate_dart(data: dict) -> str:
    colors = color_tokens(data)
    nums = num_tokens(data)
    spr = springs(data)
    lines: list[str] = []
    w = lines.append
    w("/// {GEN_HEADER}".replace("{GEN_HEADER}", GEN_HEADER))
    w("///")
    w("/// ToadMark is the shared toad-family design language. The palette values come")
    w("/// from toadPLAYER's ToadTheme (LGPL-3.0-only, zarzet) and toadHEALTH's ToadColors")
    w("/// (MIT, dukeoftoad), re-expressed; metrics follow toadPLAYER's AppTokens. No")
    w("/// upstream code is copied.")
    w("library;")
    w("")
    w("import 'package:flutter/material.dart';")
    w("")
    w("abstract final class ToadMarkTokens {")
    w("  /// ToadMark palette, hex values exactly as in toadmark.json.")
    w("  static const List<(String, Color)> palette = [")
    for kt_name, dart_name, hexval in colors:
        w(f"    ('{dart_name}', Color(0x{argb(hexval):08X})),  // {hexval.upper()}")
    w("  ];")
    w("")
    w("  /// ToadMark metric scale (dp unless noted).")
    w("  static const Map<String, double> metrics = {")
    for kt_name, dart_name, value, comment in nums:
        w(f"    '{dart_name}': {value},  // {comment}")
    w("  };")
    w("")
    w("  /// ToadMark springs: spatial overshoot slightly, effects settle flat.")
    w("  static const Map<String, (double dampingRatio, double stiffness)> springs = {")
    for name, damping, stiffness in spr:
        w(f"    '{name}': ({damping}, {stiffness}),")
    w("  };")
    w("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    data = load()
    kt = generate_kotlin(data)
    dart = generate_dart(data)
    KT_OUT.parent.mkdir(parents=True, exist_ok=True)
    DART_OUT.parent.mkdir(parents=True, exist_ok=True)
    KT_OUT.write_text(kt, encoding="utf-8")
    DART_OUT.write_text(dart, encoding="utf-8")
    print(f"wrote {KT_OUT.relative_to(ROOT)} ({len(kt.splitlines())} lines)")
    print(f"wrote {DART_OUT.relative_to(ROOT)} ({len(dart.splitlines())} lines)")


if __name__ == "__main__":
    main()
